// The primitives' reference page, generated from the specifications and the web's realizations. The page is committed, and a test fails when it is not what this writes.
import type { AccessibleName, Specification, Type, WebRealizations } from "./types.js";

const typeText = (type: Type): string =>
  type.kind === "enum" ? type.values.map((each) => `"${each}"`).join(" | ") : type.kind === "list" ? `list of ${typeText(type.element)}` : type.kind;

const nameText = (rule: AccessibleName): string => {
  const parts: Record<AccessibleName["from"], string> = {
    content: "the text inside it",
    prop: `its \`${rule.prop}\``,
    either: `its \`${rule.prop}\` when given, otherwise the text inside it`,
    none: "nothing of its own (a name comes from where it is used)",
  };

  return rule.orContainedIn === undefined ? parts[rule.from] : `${parts[rule.from]}, or a \`${rule.orContainedIn}\` around it`;
};

const contentText = (specification: Specification): string =>
  typeof specification.content === "string"
    ? { none: "none", text: "text", any: "anything" }[specification.content]
    : `only ${specification.content.only.map((each) => `\`${each}\``).join(", ")}`;

export const generateDocs = (specifications: Readonly<Record<string, Specification>>, realizations: WebRealizations): string => {
  const tagsOf = (name: string) =>
    Object.entries(realizations.primitives)
      .filter(([, each]) => each.primitive === name)
      .map(([tag]) => tag);
  const lines: string[] = [
    "<!-- GENERATED by @valancex/primitives from its specifications: do not edit; `pnpm --filter @valancex/primitives docs` writes it. -->",
    "",
    "# The primitives",
    "",
    "What each primitive is: its role, how it is named, the states it carries, its props, events and keys. This page is generated from the specifications in `packages/primitives/specs`, which are checked against the HTML Standard, ARIA in HTML and the Accessible Name and Description Computation by the primitives' tests (`docs/direction/implementation.md`, WP3). A primitive is **portable** when it is the same on every target, **web-only** or **desktop-only** when it is on one.",
    "",
    "| Primitive | Status | Role | Web tag | Named by |",
    "| --- | --- | --- | --- | --- |",
  ];

  for (const specification of Object.values(specifications)) {
    const role = specification.webRole ?? specification.role;

    lines.push(
      `| [\`${specification.name}\`](#${specification.name}) | ${specification.status} | ${role === null ? "none" : `\`${role}\``} | ${
        tagsOf(specification.name)
          .map((tag) => `\`<${tag}>\``)
          .join(", ") || "-"
      } | ${nameText(specification.accessibleName)} |`,
    );
  }

  lines.push(
    "",
    "## What `vlx` checks of a use",
    "",
    '- **`unnamed-control`**: a control whose name comes from a prop (`checkbox`, `radio`, `radiogroup`, `textfield`) has a `label`, or is inside a `<label>` that says what it is for. A reusable component that takes its name from whoever uses it says which prop that is in its contract, `component(template, { props: { label: Schema.String }, name: "label" })`: the prop must be a string every use writes (a use that omits it is reported where it is written), the template must read it (`name-unused` otherwise), and a control in it with no name of its own is not reported.',
    "- **`list-child`**: a `list` holds only `listitem`s (also under `{#if}` and `{#each}`); text or another primitive in it is reported. **`outside-container`**: a `listitem` is inside a `list` or `olist`, a `radio` inside a `radiogroup`.",
  );

  for (const specification of Object.values(specifications)) {
    lines.push("", `## ${specification.name}`, "", specification.summary, "");
    lines.push(`- **Status**: ${specification.status}${specification.within === undefined ? "" : `, inside ${specification.within.map((each) => `\`${each}\``).join(", ")}`}`);
    lines.push(
      `- **Role**: ${specification.role === null ? "none" : `\`${specification.role}\``}${specification.webRole === undefined ? "" : ` (on the web \`${specification.webRole}\`)`}`,
    );
    lines.push(`- **Accessible name**: ${nameText(specification.accessibleName)}`);
    lines.push(`- **Content**: ${contentText(specification)}`);

    if (specification.states !== undefined) {
      lines.push(
        `- **States**: ${Object.entries(specification.states)
          .map(([state, prop]) => `${state} (\`${prop}\`)`)
          .join(", ")}`,
      );
    }

    if (specification.replay !== undefined) {
      lines.push(`- **Early press**: ${specification.replay === "safe" ? "replayed once the application has started (the default)" : "dropped, not replayed"}`);
    }

    if (specification.live !== undefined) {
      lines.push(`- **Live region**: ${specification.live.politeness}${specification.live.atomic ? ", atomic" : ""}`);
    }

    if (specification.keyboard.length > 0) {
      lines.push(
        `- **Keys**: ${specification.keyboard.map((row) => `${row.key} ${row.raises === undefined ? `moves to the ${row.moves}` : `raises \`${row.raises}\``}`).join("; ")}`,
      );
    }

    const props = Object.entries(specification.props);

    if (props.length > 0) {
      lines.push("", "| Prop | Type | Required | |", "| --- | --- | --- | --- |");

      for (const [name, prop] of props) {
        const notes = [prop.controlled === true ? "the application's value" : "", prop.webOnly === true ? "web only" : "", prop.a11y === undefined ? "" : prop.a11y]
          .filter((each) => each !== "")
          .join("; ");

        lines.push(`| \`${name}\` | ${typeText(prop.type)} | ${prop.required ? "yes" : "no"} | ${notes} |`);
      }
    }

    const events = Object.entries(specification.events);

    if (events.length > 0) {
      lines.push("", "| Event | Payload | |", "| --- | --- | --- |");

      for (const [name, event] of events) {
        lines.push(`| \`${name}\` | ${event.payload === undefined ? "none" : typeText(event.payload)} | ${event.meaning ?? ""} |`);
      }
    }
  }

  return `${lines.join("\n")}\n`;
};
