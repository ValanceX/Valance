// Build time, in Node: turns the authored files into the generated ones under `.valance/`.
//
//   content.json    the content model (from content/)
//   program.json    the compiled templates (from src/*.mprx and the built-in views)
//   manifest.json   every tag, prop, scope name and command a template may use, inferred components included (for editors; nothing reads it back)
//   editor.json     where the manifest is and which file is which component (for editors)
//   wiring.json     where every name a template uses comes from, and what uses it, at both ends (for the editor: definitions and CodeLens)
//   types/          for each of the author's templates (`types/theme-toggle.d.mprx.ts`), a type for its props and events (from the compiled model, declared or inferred), for TypeScript. With
//                   `"allowArbitraryExtensions": true` and `"rootDirs": ["src", ".valance/types"]` in the project's tsconfig.json, importing a template gives that type, and a `component(…)`
//                   contract that disagrees with the template's keys is a compile-time error. Without them templates are untyped. It follows the last check, dev or build run, and is stale
//                   until the next one.
//   client.ts       the browser entry: imports the above, the author's `src/main.ts` and every stylesheet under src/
//   server.ts       the server entry: renders a pathname to a document
//
// The two entries are real files, not virtual modules, so an author can read exactly what runs.
import { existsSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { join, relative, sep } from "node:path";

import type { Config } from "./config.js";
import type { Compiled } from "./compile.js";
import { compileViews, PACKAGE_DIR, SOURCE_DIR } from "./compile.js";
import { readContent } from "./content.js";
import type { TargetId } from "./targets.js";
import { targetOf } from "./targets.js";
import type { DefinedApp } from "@valancex/common";
import { forTarget } from "@valancex/common/internal";
import type { Diagnostic } from "./diagnostics.js";
import { AppError } from "./diagnostics.js";
import type { Content } from "@valancex/common/internal";
import { ENTRY_FILE, ensureGeneratedDir, GENERATED_DIR, generated, writeIfChanged } from "./project.js";
import { themeOf } from "./theme.js";
import { buildWiring } from "./wiring.js";

/** The layout of the portable core on the web: `column` and `row` are custom elements, and this is what they are (`@valancex/common`'s web vocabulary). It is the library's layer, the first of the
 *  three (library, theme, application): a theme's gap replaces the default here, and a project's own styles, which are in no layer, win over both. */
const CORE_CSS = `/* Generated by \`valance\`. The web's realization of the portable core's layout components. */
@layer vlx-library, vlx-theme, vlx-app;

@layer vlx-library {
  vlx-column {
    display: flex;
    flex-direction: column;
    gap: 0.5rem;
  }

  vlx-row {
    display: flex;
    flex-direction: row;
    align-items: center;
    gap: 0.5rem;
  }
}
`;

/** The theme's stylesheet. A theme with a problem is reported by \`check\` (and refused by \`build\`); the page gets no theme meanwhile rather than a half of one. */
const themeStylesheet = (root: string): string => themeOf(root).css ?? "/* The theme has a problem: run `vlx check`. */\n";

/** The stylesheets the web loads: every one under `src/` except those in another target's directory (`src/desktop/`). */
const stylesheets = (root: string): ReadonlyArray<string> =>
  existsSync(join(root, SOURCE_DIR))
    ? readdirSync(join(root, SOURCE_DIR), { recursive: true, encoding: "utf8" })
        .map((file) => file.split(sep).join("/"))
        .filter((file) => file.endsWith(".css") && !file.startsWith("desktop/"))
        .sort()
        .map((file) => `${SOURCE_DIR}/${file}`)
    : [];

export const hasEntry = (root: string): boolean => existsSync(join(root, ENTRY_FILE));

const clientSource = (root: string, config?: Config, record = false): string => `// Generated by \`valance\`. Do not edit: it is rewritten whenever the project changes.
// @ts-nocheck
import { start } from "@valancex/common/client";
import content from "./content.json";
import program from "./${programFile(config, "web")}";
import "./theme.css";
import "./core.css";
${hasEntry(root) ? `import author from "../${ENTRY_FILE}";\n` : "const author = undefined;\n"}${stylesheets(root)
  .map((file) => `import "../${file}";\n`)
  .join("")}
${record ? `// \`vlx dev --record\`: development only. A build rewrites this entry without it.\nconst { recording } = await import("@valancex/common/record");\nconst record = recording(program, ${JSON.stringify(config?.record.redact ?? { scope: [], commands: [] })});\n` : ""}await start({ content, program, author${record ? ", record" : ""} });
`;

const desktopSource = (root: string, config?: Config): string => `// Generated by \`valance\`. Do not edit: it is rewritten whenever the project changes.
// @ts-nocheck
import { start } from "@valancex/common/desktop";
import theme from "./theme.desktop.json";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import content from "./content.json";
import program from "./${programFile(config, "desktop")}";
${hasEntry(root) ? `import author from "../${ENTRY_FILE}";\n` : "const author = undefined;\n"}
// the MESH runtime's module sits beside the built engine (vlx build copies it there)
const wasm = new Uint8Array(readFileSync(new URL("./mesh-runtime.wasm", import.meta.url)));
// (and the project's public/ files, which images are drawn from)
const assets = fileURLToPath(new URL("./public/", import.meta.url));
await start({ content, program, author, wasm, assets, theme: theme ?? undefined });
// the window is closed: nothing the application left open keeps the engine alive
process.exit(0);
`;

const serverSource = (root: string, config?: Config): string => `// Generated by \`valance\`. Do not edit: it is rewritten whenever the project changes.
// @ts-nocheck
import { createRenderer, pathsOf } from "@valancex/common/server";
import content from "./content.json";
import program from "./${programFile(config, "web")}";
${hasEntry(root) ? `import author from "../${ENTRY_FILE}";\n` : "const author = undefined;\n"}
export const render = createRenderer({ content, program, author });
export const paths = () => pathsOf(content);
export { content };
`;

export const writeContent = (root: string, content: Content): boolean => writeIfChanged(generated(root, "content.json"), `${JSON.stringify(content, null, 2)}\n`);

/** The content stage alone: it does not need the author's code. */
export const generateContent = (root: string, config: Config): Content => {
  ensureGeneratedDir(root);

  const content = readContent(root, config);

  writeContent(root, content);

  return content;
};

/** The file a target's compiled program is in: `program.json` for a project of one target (as it always was), `program.<target>.json` for one of several. */
export const programFile = (config: Config | undefined, id: TargetId): string => ((config?.targets.length ?? 1) > 1 ? `program.${id}.json` : "program.json");
const manifestFile = (config: Config | undefined, id: TargetId): string => ((config?.targets.length ?? 1) > 1 ? `manifest.${id}.json` : "manifest.json");
const wiringFile = (config: Config | undefined, id: TargetId): string => ((config?.targets.length ?? 1) > 1 ? `wiring.${id}.json` : "wiring.json");

/** The templates stage: needs the author's definition (the manifest derives from its state and commands). One program per target; the state, the commands and the content are shared. */
export const generateProgram = async (root: string, author: DefinedApp | undefined, config?: Config, only?: ReadonlyArray<TargetId>): Promise<ReadonlyArray<string>> => {
  ensureGeneratedDir(root);

  const targets = (config?.targets ?? ["web"]).filter((id) => only === undefined || only.includes(id));
  const compiledAll: Array<{ readonly id: TargetId; readonly compiled: Compiled }> = [];
  const problems: Array<Diagnostic> = [];

  for (const id of targets) {
    const target = targetOf(id);

    try {
      compiledAll.push({ id, compiled: await compileViews(root, forTarget(author, id), target.vocabulary, target.views) });
    } catch (error) {
      if (!(error instanceof AppError)) {
        throw error;
      }

      problems.push(...error.diagnostics);
    }
  }

  // a theme the project writes is checked with the templates: a mistake in it is as much the project's as one in a layout
  problems.push(...(themeOf(root).custom ? themeOf(root).diagnostics : []));

  if (problems.length > 0) {
    throw new AppError(problems);
  }

  const readme = join(PACKAGE_DIR, "README.md");
  const docs = existsSync(readme) ? { file: relative(root, readme).split(sep).join("/"), lines: readFileSync(readme, "utf8").split("\n") } : undefined;
  const editor: Array<{ readonly id: TargetId; readonly model: string; readonly wiring: string; readonly components: unknown }> = [];

  for (const { id, compiled } of compiledAll) {
    writeIfChanged(generated(root, programFile(config, id)), `${JSON.stringify(compiled.program)}\n`);
    writeIfChanged(generated(root, manifestFile(config, id)), `${JSON.stringify(compiled.manifest, null, 2)}\n`);
    // Where every name came from and what uses it, at both ends, for the editor. The framework's own names point into the README that ships with the package.
    writeIfChanged(generated(root, wiringFile(config, id)), `${JSON.stringify(buildWiring(root, forTarget(author, id), compiled, docs), null, 2)}\n`);
    editor.push({ id, model: `${GENERATED_DIR}/${manifestFile(config, id)}`, wiring: `${GENERATED_DIR}/${wiringFile(config, id)}`, components: compiled.files });
  }

  // The one file an editor reads to know the project: where the manifest is, and which file is the template of which component. The conventions stay here, not copied into every editor. For a project
  // of several targets the first one is what the editor reads (`model`, `wiring`), and `targets` lists each.
  const first = editor[0];

  // Only a pass over every target writes it (a pass over one, as `vlx dev --web` is, would leave the others out of it).
  if (first !== undefined && editor.length === (config?.targets ?? ["web"]).length) {
    writeIfChanged(
      generated(root, "editor.json"),
      `${JSON.stringify({ version: 1, model: first.model, components: first.components, wiring: first.wiring, ...(editor.length > 1 ? { targets: Object.fromEntries(editor.map((each) => [each.id, { model: each.model, wiring: each.wiring, components: each.components }])) } : {}) }, null, 2)}\n`,
    );
  }

  writeTemplateTypes(
    root,
    compiledAll.map((each) => each.compiled),
  );

  return [...new Set(compiledAll.flatMap((each) => each.compiled.components))];
};

const union = (names: ReadonlyArray<string>): string => (names.length === 0 ? "never" : names.map((name) => JSON.stringify(name)).join(" | "));

/** The declaration of one template's type: its props and events as the names TypeScript checks a contract's keys against. */
export const templateType = (props: ReadonlyArray<string>, events: ReadonlyArray<string>): string =>
  `// Generated by \`vlx\`. Do not edit: it is rewritten by every check, dev or build run, and is stale until the next one.
declare const template: import("@valancex/common").Template<${union(props)}, ${union(events)}>;
export default template;
`;

/**
 * Where a template's type is written: under `.valance/types/`, named so that `rootDirs` makes it the declaration of the template beside which it would sit, and `allowArbitraryExtensions` reads it
 * as the declaration of a `.mprx` file (`src/a/b.mprx` → `types/a/b.d.mprx.ts`).
 */
const typePath = (file: string): string => `types/${file.replace(new RegExp(`^${SOURCE_DIR}/`), "").replace(/\.mprx$/, ".d.mprx.ts")}`;

/** Writes the type of each of the author's templates, and removes the type of one that is gone. */
const writeTemplateTypes = (root: string, all: ReadonlyArray<Compiled>): void => {
  const written = new Set<string>();

  for (const compiled of all) {
    const components = (
      compiled.manifest as { readonly components: Readonly<Record<string, { readonly props: Record<string, unknown>; readonly events: Record<string, unknown> }>> }
    ).components;

    for (const template of compiled.templates.filter((each) => !each.builtIn)) {
      const entry = components[template.component];
      const path = typePath(template.file);

      written.add(path);
      writeIfChanged(generated(root, path), templateType(Object.keys(entry?.props ?? {}), Object.keys(entry?.events ?? {})));
    }
  }

  const dir = generated(root, "types");

  if (existsSync(dir)) {
    for (const file of readdirSync(dir, { recursive: true, encoding: "utf8" }).filter((each) => each.endsWith(".d.mprx.ts"))) {
      if (!written.has(`types/${file.split(sep).join("/")}`)) {
        rmSync(join(dir, file), { force: true });
      }
    }
  }
};

/** The entries; rewritten when `src/main.ts` or a stylesheet is added or removed. Each target has its own: the web's two (`client.ts`, `server.ts`), the desktop's one (`desktop.ts`). */
export const generateEntries = (root: string, config?: Config, options?: { readonly record?: boolean }): boolean => {
  ensureGeneratedDir(root);

  const targets = config?.targets ?? ["web"];

  return [
    ...(targets.includes("web")
      ? [
          writeIfChanged(generated(root, "core.css"), CORE_CSS),
          writeIfChanged(generated(root, "theme.css"), themeStylesheet(root)),
          writeIfChanged(generated(root, "client.ts"), clientSource(root, config, options?.record === true)),
          writeIfChanged(generated(root, "server.ts"), serverSource(root, config)),
        ]
      : []),
    ...(targets.includes("desktop")
      ? [
          writeIfChanged(generated(root, "theme.desktop.json"), `${JSON.stringify(themeOf(root).desktop ?? null)}\n`),
          writeIfChanged(generated(root, "desktop.ts"), desktopSource(root, config)),
        ]
      : []),
  ].some(Boolean);
};
