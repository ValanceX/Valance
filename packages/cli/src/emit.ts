// Build time, in Node: turns the authored files into the generated ones under `.valance/`.
//
//   content.json    the content model (from content/)
//   program.json    the compiled templates (from src/*.mprx and the built-in views)
//   manifest.json   every tag, prop, scope name and command a template may use, inferred components included (for editors; nothing reads it back)
//   editor.json     where the manifest is and which file is which component (for editors)
//   wiring.json     where every name a template uses comes from, and what uses it, at both ends (for the editor: definitions and CodeLens)
//   types/          for each of the author's templates (`types/theme-toggle.d.mprx.ts`), a type for its props and events (from the compiled model, declared or inferred), for TypeScript. With
//                   `"allowArbitraryExtensions": true` and `"rootDirs": ["src", ".valance/types"]` in the project's tsconfig.json, importing a template gives that type, and a `component(…)`
//                   contract that disagrees with the template's keys is a compile-time error. Without them templates are untyped. It follows the last check, dev or build run, and is stale
//                   until the next one.
//   client.ts       the browser entry: imports the above, the author's `src/main.ts` and every stylesheet under src/
//   server.ts       the server entry: renders a pathname to a document
//
// The two entries are real files, not virtual modules, so an author can read exactly what runs.
import { existsSync, readdirSync, readFileSync, rmSync } from "node:fs";
import { join, relative, sep } from "node:path";

import type { Config } from "./config.js";
import type { Compiled } from "./compile.js";
import { compileViews, PACKAGE_DIR, SOURCE_DIR } from "./compile.js";
import { readContent } from "./content.js";
import type { DefinedApp } from "@valancex/common";
import type { Content } from "./model.js";
import { ENTRY_FILE, ensureGeneratedDir, GENERATED_DIR, generated, writeIfChanged } from "./project.js";
import { buildWiring } from "./wiring.js";

const stylesheets = (root: string): ReadonlyArray<string> =>
  existsSync(join(root, SOURCE_DIR))
    ? readdirSync(join(root, SOURCE_DIR), { recursive: true, encoding: "utf8" })
        .filter((file) => file.endsWith(".css"))
        .sort()
        .map((file) => `${SOURCE_DIR}/${file}`)
    : [];

export const hasEntry = (root: string): boolean => existsSync(join(root, ENTRY_FILE));

const clientSource = (root: string): string => `// Generated by \`valance\`. Do not edit: it is rewritten whenever the project changes.
// @ts-nocheck
import { start } from "@valancex/cli/client";
import content from "./content.json";
import program from "./program.json";
${hasEntry(root) ? `import author from "../${ENTRY_FILE}";\n` : "const author = undefined;\n"}${stylesheets(root)
  .map((file) => `import "../${file}";\n`)
  .join("")}
await start({ content, program, author });
`;

const serverSource = (root: string): string => `// Generated by \`valance\`. Do not edit: it is rewritten whenever the project changes.
// @ts-nocheck
import { createRenderer, pathsOf } from "@valancex/cli/server";
import content from "./content.json";
import program from "./program.json";
${hasEntry(root) ? `import author from "../${ENTRY_FILE}";\n` : "const author = undefined;\n"}
export const render = createRenderer({ content, program, author });
export const paths = () => pathsOf(content);
export { content };
`;

export const writeContent = (root: string, content: Content): boolean => writeIfChanged(generated(root, "content.json"), `${JSON.stringify(content, null, 2)}\n`);

/** The content stage alone: it does not need the author's code. */
export const generateContent = (root: string, config: Config): Content => {
  ensureGeneratedDir(root);

  const content = readContent(root, config);

  writeContent(root, content);

  return content;
};

/** The templates stage: needs the author's definition (the manifest derives from its state and commands). */
export const generateProgram = async (root: string, author: DefinedApp | undefined): Promise<ReadonlyArray<string>> => {
  ensureGeneratedDir(root);

  const compiled = await compileViews(root, author);

  writeIfChanged(generated(root, "program.json"), `${JSON.stringify(compiled.program)}\n`);
  writeIfChanged(generated(root, "manifest.json"), `${JSON.stringify(compiled.manifest, null, 2)}\n`);
  // The one file an editor reads to know the project: where the manifest is, and which file is the template of which component. The conventions stay here, not copied into every editor.
  writeIfChanged(
    generated(root, "editor.json"),
    `${JSON.stringify({ version: 1, model: `${GENERATED_DIR}/manifest.json`, components: compiled.files, wiring: `${GENERATED_DIR}/wiring.json` }, null, 2)}\n`,
  );

  writeTemplateTypes(root, compiled);

  // Where every name came from and what uses it, at both ends, for the editor. The framework's own names point into the README that ships with the package.
  const readme = join(PACKAGE_DIR, "README.md");
  const docs = existsSync(readme) ? { file: relative(root, readme).split(sep).join("/"), lines: readFileSync(readme, "utf8").split("\n") } : undefined;

  writeIfChanged(generated(root, "wiring.json"), `${JSON.stringify(buildWiring(root, author, compiled, docs), null, 2)}\n`);

  return compiled.components;
};

const union = (names: ReadonlyArray<string>): string => (names.length === 0 ? "never" : names.map((name) => JSON.stringify(name)).join(" | "));

/** The declaration of one template's type: its props and events as the names TypeScript checks a contract's keys against. */
export const templateType = (props: ReadonlyArray<string>, events: ReadonlyArray<string>): string =>
  `// Generated by \`vlx\`. Do not edit: it is rewritten by every check, dev or build run, and is stale until the next one.
declare const template: import("@valancex/common").Template<${union(props)}, ${union(events)}>;
export default template;
`;

/**
 * Where a template's type is written: under `.valance/types/`, named so that `rootDirs` makes it the declaration of the template beside which it would sit, and `allowArbitraryExtensions` reads it
 * as the declaration of a `.mprx` file (`src/a/b.mprx` → `types/a/b.d.mprx.ts`).
 */
const typePath = (file: string): string => `types/${file.replace(new RegExp(`^${SOURCE_DIR}/`), "").replace(/\.mprx$/, ".d.mprx.ts")}`;

/** Writes the type of each of the author's templates, and removes the type of one that is gone. */
const writeTemplateTypes = (root: string, compiled: Compiled): void => {
  const components = (compiled.manifest as { readonly components: Readonly<Record<string, { readonly props: Record<string, unknown>; readonly events: Record<string, unknown> }>> })
    .components;
  const written = new Set<string>();

  for (const template of compiled.templates.filter((each) => !each.builtIn)) {
    const entry = components[template.component];
    const path = typePath(template.file);

    written.add(path);
    writeIfChanged(generated(root, path), templateType(Object.keys(entry?.props ?? {}), Object.keys(entry?.events ?? {})));
  }

  const dir = generated(root, "types");

  if (existsSync(dir)) {
    for (const file of readdirSync(dir, { recursive: true, encoding: "utf8" }).filter((each) => each.endsWith(".d.mprx.ts"))) {
      if (!written.has(`types/${file.split(sep).join("/")}`)) {
        rmSync(join(dir, file), { force: true });
      }
    }
  }
};

/** The entries; rewritten when `src/main.ts` or a stylesheet is added or removed. */
export const generateEntries = (root: string): boolean => {
  ensureGeneratedDir(root);

  return [writeIfChanged(generated(root, "client.ts"), clientSource(root)), writeIfChanged(generated(root, "server.ts"), serverSource(root))].some(Boolean);
};
