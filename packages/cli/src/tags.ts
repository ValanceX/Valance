// The tags a template may write, per target, as a table: the one reference for what a vocabulary offers. It is generated from the vocabulary itself (the web's realization table, or the
// Desktop PORT's manifest), so it cannot say a tag exists that does not, or leave out one that does. The CLI guide embeds it between markers and a test keeps the two equal.
import { namesOf } from "@valancex/common/internal";
import type { Vocabulary } from "@valancex/common/internal";

import { manifestOf } from "./compile.js";
import type { Target } from "./targets.js";
import { TARGETS } from "./targets.js";

interface Typed {
  readonly kind?: string;
  readonly of?: Typed;
  readonly values?: ReadonlyArray<unknown>;
}

interface Entry {
  readonly props?: Readonly<Record<string, { readonly type?: Typed; readonly required?: boolean }>>;
  readonly events?: Readonly<Record<string, { readonly payload?: Typed }>>;
}

const typeText = (type: Typed | undefined): string =>
  type === undefined
    ? "any"
    : type.kind === "list"
      ? `list of ${typeText(type.of)}`
      : type.values === undefined
        ? (type.kind ?? "any")
        : type.values.map((value) => JSON.stringify(value)).join(" | ");

/** One tag of a vocabulary: its name, the element it becomes (the web's only), its props (a `*` marks one every use must write) and its events with their payloads. */
export interface Tag {
  readonly name: string;
  readonly element: string;
  readonly props: ReadonlyArray<string>;
  readonly events: ReadonlyArray<string>;
}

/** The primitives of a vocabulary in the order it declares them. */
export const tagsOf = (vocabulary: Vocabulary): ReadonlyArray<Tag> => {
  const components = ("tags" in vocabulary ? manifestOf(undefined, vocabulary).components : vocabulary.components) as Readonly<Record<string, Entry>>;

  return namesOf(vocabulary).map((name) => {
    const entry = components[name] ?? {};

    return {
      name,
      element: "tags" in vocabulary ? `\`<${(vocabulary.tags[name] as { readonly element: string }).element}>\`` : "",
      props: Object.entries(entry.props ?? {}).map(([prop, each]) => `\`${prop}\`${each.required === true ? "*" : ""} (${typeText(each.type)})`),
      events: Object.entries(entry.events ?? {}).map(([event, each]) => `\`${event}\`${each.payload === undefined ? "" : ` (${typeText(each.payload)})`}`),
    };
  });
};

/** A target's tags as a Markdown table. */
export const tagTable = (target: Target): string => {
  const web = "tags" in target.vocabulary;
  const rows = tagsOf(target.vocabulary).map(
    (each) => `| \`${each.name}\` |${web ? ` ${each.element} |` : ""} ${each.props.join(", ") || "none"} | ${each.events.join(", ") || "none"} |`,
  );

  return [`| Tag |${web ? " Becomes |" : ""} Props | Events |`, `|---|${web ? "---|" : ""}---|---|`, ...rows].join("\n");
};

/** Every target's table with a heading each: what the CLI guide embeds. */
export const tagReference = (): string =>
  TARGETS.map((target) => `**${target.label}** (${tagsOf(target.vocabulary).length} tags). A \`*\` marks a prop every use must write.\n\n${tagTable(target)}`).join("\n\n");

export const TAGS_BEGIN = "<!-- tags:begin (generated by src/tags.ts; run `pnpm docs:tags`) -->";
export const TAGS_END = "<!-- tags:end -->";
