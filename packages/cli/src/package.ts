// `vlx package`: the desktop target as something to hand to a person. The engine becomes one executable (Node's single executable application: the engine bundled to one file, with the MESH
// runtime's module inside as an asset, injected into a `node` binary), set beside the Desktop PORT's window program. Unsigned: signing and notarizing are not done here (the artifacts say so).
import { build as bundle } from "vite";
import { execFileSync } from "node:child_process";
import { chmodSync, copyFileSync, cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { delimiter, join } from "node:path";

import type { Entry } from "./archive.js";
import { checksums, tarGz, zip } from "./archive.js";
import { loadAuthor } from "./author.js";
import { build } from "./build.js";
import { loadConfig } from "./config.js";
import { AppError } from "./diagnostics.js";
import { hasEntry } from "./emit.js";
import { ENTRY_FILE, GENERATED_DIR, OUTPUT_DIR } from "./project.js";
import { programFile } from "./emit.js";
import { createLoader, templates } from "./vite.js";

export const PLATFORMS = ["linux-x64", "win32-x64"] as const;
export type Platform = (typeof PLATFORMS)[number];

export interface PackageOptions {
  /** The platform the package is for; by default the one this runs on. */
  readonly platform?: string;
  /** The Desktop PORT's window program for that platform (`vlx-window`); by default `VLX_WINDOW`, else `vlx-window` on the PATH. */
  readonly window?: string;
  /** A `node` binary of the same version for that platform; by default the one running this, which is only right for the platform this runs on. */
  readonly node?: string;
  /** Also write the package as one file: a `.tar.gz` for Linux, a `.zip` for Windows, with its SHA-256 beside it. */
  readonly archive?: boolean;
}

export interface Packaged {
  readonly dir: string;
  readonly files: ReadonlyArray<string>;
  readonly notes: ReadonlyArray<string>;
}

const hostPlatform = (): string => `${process.platform}-${process.arch}`;

const fail = (message: string): never => {
  throw new AppError([{ file: "valance.desktop.json", line: 0, column: 0, code: "package", message }]);
};

/** A program on the PATH, as the shell would find it. */
const onPath = (name: string): string | undefined =>
  (process.env["PATH"] ?? "")
    .split(delimiter)
    .map((dir) => join(dir, name))
    .find((candidate) => existsSync(candidate));

/** The entry of the packaged engine: the generated desktop entry, with the MESH runtime's module read from the executable's own assets (a single file has nothing beside it). */
const seaSource = (root: string, config: ReturnType<typeof loadConfig>): string => `// Generated by \`vlx package\`. Do not edit.
// @ts-nocheck
import { getRawAsset } from "node:sea";
import { dirname, join } from "node:path";
import { start } from "@valancex/common/desktop";
import content from "./content.json";
import program from "./${programFile(config, "desktop")}";
${hasEntry(root) ? `import author from "../${ENTRY_FILE}";\n` : "const author = undefined;\n"}
const wasm = new Uint8Array(getRawAsset("mesh-runtime.wasm"));

// the project's public/ files sit beside the executable
const assets = join(dirname(process.execPath), "public");

start({ content, program, author, wasm, assets }).then(
  () => process.exit(0),
  (error) => {
    console.error("the engine stopped:", error);
    process.exit(1);
  },
);
`;

/** Every file under `dir` as an archive entry inside `top/`, in a stable order (a program keeps its executable bit). */
const entriesOf = (dir: string, top: string, at = ""): ReadonlyArray<Entry> =>
  readdirSync(join(dir, at))
    .sort()
    .flatMap((name) => {
      const relative = at === "" ? name : `${at}/${name}`;
      const file = join(dir, relative);

      return statSync(file).isDirectory()
        ? entriesOf(dir, top, relative)
        : [{ path: `${top}/${relative}`, data: readFileSync(file), mode: statSync(file).mode & 0o111 ? 0o755 : 0o644 }];
    });

export const packageDesktop = async (root: string, options: PackageOptions = {}): Promise<Packaged> => {
  const config = loadConfig(root);

  if (!config.targets.includes("desktop")) {
    return fail("this project has no desktop target (vlx generate target desktop)");
  }

  const platform = options.platform ?? hostPlatform();

  if (!(PLATFORMS as ReadonlyArray<string>).includes(platform)) {
    return fail(`cannot package for ${platform}: the platforms are ${PLATFORMS.join(", ")}`);
  }

  const windows = platform.startsWith("win32");
  const node = options.node ?? (platform === hostPlatform() ? process.execPath : undefined);
  const window = options.window ?? process.env["VLX_WINDOW"] ?? onPath(windows ? "vlx-window.exe" : "vlx-window");

  if (node === undefined) {
    return fail(`packaging for ${platform} from ${hostPlatform()} needs a node binary of this version for ${platform}: --node <path>`);
  }
  if (window === undefined || !existsSync(window)) {
    return fail(`no window program: build it from the PORT repository (cargo build --release --bin vlx-window) and give its path with --window <path> (or set VLX_WINDOW)`);
  }

  // The engine, built first: the content, the program and the entries are the project's as they are now.
  await build(root, { targets: ["desktop"] });

  const work = join(root, GENERATED_DIR, "package");

  rmSync(work, { recursive: true, force: true });
  mkdirSync(work, { recursive: true });
  writeFileSync(join(root, GENERATED_DIR, "desktop.sea.ts"), seaSource(root, config));

  // Loading the author's definition once checks it still loads; the bundle below is the one that ships.
  const loader = await createLoader(root, config);

  try {
    await loadAuthor(loader, root);
  } finally {
    await loader.close();
  }

  await bundle({
    root,
    configFile: false,
    publicDir: false,
    logLevel: "warn",
    plugins: [templates(root)],
    cacheDir: join(root, GENERATED_DIR, "cache"),
    ssr: { noExternal: true, target: "node" },
    esbuild: { keepNames: true },
    build: {
      ssr: join(root, GENERATED_DIR, "desktop.sea.ts"),
      outDir: work,
      emptyOutDir: false,
      target: "node22",
      // W10: the engine is minified (half the bytes; start-up measured no worse, 2026-10-24). Names are kept: errors and their `_tag` are read by name.
      minify: "esbuild",
      rollupOptions: { output: { format: "cjs", entryFileNames: "engine.cjs" } },
    },
  });

  const wasm = createRequire(createRequire(join(root, "package.json")).resolve("@valancex/common/package.json")).resolve("@valancex/mesh-runtime/mesh-runtime.wasm");

  writeFileSync(
    join(work, "sea-config.json"),
    JSON.stringify({ main: join(work, "engine.cjs"), output: join(work, "engine.blob"), disableExperimentalSEAWarning: true, assets: { "mesh-runtime.wasm": wasm } }),
  );
  execFileSync(process.execPath, ["--experimental-sea-config", join(work, "sea-config.json")], { stdio: "pipe" });

  const out = join(root, OUTPUT_DIR, "package", platform);

  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });

  const engine = join(out, windows ? "vlx-engine.exe" : "vlx-engine");
  const app = join(out, `${config.name.replace(/[^\w.-]+/g, "-")}${windows ? ".exe" : ""}`);

  copyFileSync(node, engine);
  chmodSync(engine, 0o755);

  const injector = "postject"; // (no type declarations of its own)
  const { inject } = (await import(injector)) as { readonly inject: (file: string, name: string, blob: Buffer, options: { readonly sentinelFuse: string }) => Promise<void> };

  await inject(engine, "NODE_SEA_BLOB", readFileSync(join(work, "engine.blob")), { sentinelFuse: "NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2" });
  copyFileSync(window, app);
  chmodSync(app, 0o755);

  // The files images are drawn from, beside the engine.
  const publicDir = join(root, "public");

  if (existsSync(publicDir)) {
    cpSync(publicDir, join(out, "public"), { recursive: true });
  }

  const files = [engine, app].map((file) => file.slice(out.length + 1));
  const notes = ["unsigned: macOS notarization and Windows signing are not done here; an unsigned program draws a warning on first run"];

  if (options.archive === true) {
    const stem = `${config.name.replace(/[^\w.-]+/g, "-")}-${platform}`;
    const archive = `${stem}.${windows ? "zip" : "tar.gz"}`;
    const data = (windows ? zip : tarGz)(entriesOf(out, stem));

    writeFileSync(join(root, OUTPUT_DIR, "package", archive), data);
    writeFileSync(join(root, OUTPUT_DIR, "package", `${archive}.sha256`), checksums([{ name: archive, data }]));
    files.push(`../${archive}`, `../${archive}.sha256`);
    notes.push(
      `${archive} is the package as one file, with its SHA-256 beside it; the checksum says the file is the one that was made, not who made it (that is what signing is for)`,
    );
  }

  return { dir: out, files, notes };
};
